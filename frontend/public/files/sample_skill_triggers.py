# -*- coding: utf-8 -*-
"""
各スキルのトリガーサンプルコード

backcast.py のプレイグラウンドセルにコピー＆ペーストで実行可能。
各コードブロックは独立して実行できる。

前提: import game_setup as bt
"""

# ============================================================
# サンドボックス — 基本操作を体験
# ============================================================

# --- SANDBOX_001: マーケットへようこそ ---
# backcast.py 起動時に自動発火（chart セルが実行される）
bt.chart("7203")

# --- SANDBOX_002: 初めての購入 ---
bt.buy()

# --- SANDBOX_003: 買値を確認する ---
# 前提: buy() 済み → step() で約定 → trades() で確認
bt.step()
bt.trades()

# --- SANDBOX_004: 初めての売却 ---
bt.sell()

# --- SANDBOX_005: チャートで振り返る ---
# 前提: SANDBOX_003 + SANDBOX_004 が完了していること
bt.chart("7203")

# --- SANDBOX_006: サンドボックス卒業 ---
# 001〜005 が全て完了すると自動発火（_check_graduations）
# ユーザー操作不要

# ============================================================
# ブリッジ — 裏側の仕組みを学ぶ
# ============================================================

# --- BRIDGE_001: データの正体 ---
# 前提: chart() でデータが読み込まれていること
bt.reveal_data()

# --- BRIDGE_002: 自分でデータを取得 ---
df_sony = bt.get_stock_daily("6758")
df_sony.head()

# --- BRIDGE_003: フルモードへ ---
# BRIDGE_002 完了時に自動発火（_check_graduations）
# ユーザー操作不要

# ============================================================
# FAIL — 失敗から学ぶ
# ============================================================

# --- FAIL_001: 初めての含み損 ---
# 前提: buy() 済み → 数日 step() して株価が下がる
bt.buy()
for _ in range(5):
    bt.step()
bt.trades()  # 含み損があればここで FAIL_001 発火
# もしくは bt.step() の _check_unrealized_loss でも発火

# --- FAIL_002: 初めての損切り ---
# 前提: 含み損の状態で売却
bt.sell()  # closed_trades に pl < 0 があれば発火

# --- FAIL_003: 初めての破産 ---
# equity <= 0 になると BackcastPro が例外を出し、
# step() の try/except で FAIL_003 が発火する
# （意図的に起こすには全資金をレバレッジ取引に投入して暴落を待つ）
try:
    bt.step()
except Exception:
    pass  # FAIL_003 はこの前に発火済み
